#pragma once

#include <string>

namespace CS2 { struct Runtime; }

namespace CS2::WebRadar {

// Start/stop local HTTP server that serves radar_webapp + /api/live JSON.
bool Start(int port);
void Stop();
bool IsRunning() noexcept;
int Port() noexcept;

// Queue an already-published immutable snapshot. Formatting happens on the
// radar server thread, not in the DMA acquisition lane.
void SubmitSnapshot(const Runtime& snapshot);

// LAN URL e.g. http://192.168.1.10:8080/#token
std::string LocalUrl();
std::string LocalIp();
// Cloudflare public URL when tunnel is up (empty otherwise).
std::string PublicUrl();
std::string AccessToken();

bool StartCloudflare();
void StopCloudflare();
bool CloudflareRunning() noexcept;
std::string CloudflareStatus();

// Build a JSON snapshot. The live path is generated by the radar server thread.
std::string BuildLiveJson(const Runtime& runtime);
std::string BuildLiveJson();

} // namespace CS2::WebRadar
