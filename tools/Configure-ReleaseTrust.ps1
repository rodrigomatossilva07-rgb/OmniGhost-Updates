[CmdletBinding(SupportsShouldProcess = $true)]
param(
    [string]$ProjectDir = '',
    [string]$CertificateThumbprint = $env:OMNIGHOST_SIGNING_THUMBPRINT,
    [string]$SecondaryCertificateThumbprint = ''
)

$ErrorActionPreference = 'Stop'
[Console]::OutputEncoding = New-Object Text.UTF8Encoding($false)
. (Join-Path $PSScriptRoot 'ReleaseTrustTools.ps1')
if ([string]::IsNullOrWhiteSpace($ProjectDir)) { $ProjectDir = Split-Path -Parent $PSScriptRoot }
$ProjectDir = [IO.Path]::GetFullPath($ProjectDir)
$certificate = Get-ReleaseSigningCertificate -Thumbprint $CertificateThumbprint -RequirePrivateKey
$secondary = $null
if (-not [string]::IsNullOrWhiteSpace($SecondaryCertificateThumbprint)) {
    $secondary = Get-ReleaseSigningCertificate -Thumbprint $SecondaryCertificateThumbprint
    if ($secondary.Thumbprint -ceq $certificate.Thumbprint) { throw 'Primary and secondary certificates must differ.' }
}
$policyPath = Join-Path $ProjectDir 'config\release\release-publish.json'
$headerPath = Join-Path $ProjectDir 'src\updater\release_trust.h'
$policy = [IO.File]::ReadAllText($policyPath, [Text.Encoding]::UTF8) | ConvertFrom-Json
$policy.requireAuthenticode = $true
$policy.requireManifestSignature = $true
$policy.signingCertificateThumbprint = $certificate.Thumbprint.ToUpperInvariant()
$policy.expectedPublisherSubject = $certificate.Subject
$policy.secondarySigningCertificateThumbprint = if ($null -ne $secondary) { $secondary.Thumbprint.ToUpperInvariant() } else { '' }
$policy.secondaryExpectedPublisherSubject = if ($null -ne $secondary) { $secondary.Subject } else { '' }
$publicDer = [Convert]::ToBase64String($certificate.RawData)
$secondaryDer = if ($null -ne $secondary) { [Convert]::ToBase64String($secondary.RawData) } else { '' }
$secondaryConfigured = if ($null -ne $secondary) { 'true' } else { 'false' }
$header = @"
#pragma once

// Generated by tools/Configure-ReleaseTrust.ps1; public certificates only.
// Private keys remain in the Windows certificate store.
namespace OmniGhost::Update::ReleaseTrust {
inline constexpr char PublisherSubject[] = $(ConvertTo-CppStringLiteral $certificate.Subject);
inline constexpr char CertificateThumbprint[] = $(ConvertTo-CppStringLiteral $policy.signingCertificateThumbprint);
inline constexpr char PublicCertificateDerBase64[] = $(ConvertTo-CppStringLiteral $publicDer);
inline constexpr char SecondaryPublisherSubject[] = $(ConvertTo-CppStringLiteral $policy.secondaryExpectedPublisherSubject);
inline constexpr char SecondaryCertificateThumbprint[] = $(ConvertTo-CppStringLiteral $policy.secondarySigningCertificateThumbprint);
inline constexpr char SecondaryPublicCertificateDerBase64[] = $(ConvertTo-CppStringLiteral $secondaryDer);
inline constexpr bool Configured = true;
inline constexpr bool SecondaryConfigured = $secondaryConfigured;
}
"@
if ($PSCmdlet.ShouldProcess($ProjectDir, 'Pin the public release certificates in policy and client source')) {
    [IO.File]::WriteAllText($policyPath, ($policy | ConvertTo-Json -Depth 10) + "`n", (New-Object Text.UTF8Encoding($false)))
    [IO.File]::WriteAllText($headerPath, $header + "`n", (New-Object Text.UTF8Encoding($false)))
    Write-Host '[OmniGhost Trust] Public release identity configured. Commit both files and rebuild before Publish.'
}
